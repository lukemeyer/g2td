"""Bundle the art pack (art/pack/pack.json and its pictures) into src/pack.ts, which the
renderer (src/render/map.ts) draws from in the game, the map editor and the art library.

    .venv/bin/python -I tools/pack_build.py

Every picture becomes rows of hex levels ('.' see-through), exactly as drawn: nothing is
scaled. Checks that each picture exists and that pieces fit their footprints.
"""
import json
import os
import sys

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PACK = os.path.join(ROOT, "art", "pack")
OUT = os.path.join(ROOT, "src", "pack.ts")


def rows(rel):
    path = os.path.join(PACK, rel)
    if not os.path.exists(path): sys.exit(f"pack: no picture {rel}")
    im = Image.open(path).convert("LA")
    p = im.load()
    return ["".join("." if p[x, y][1] < 128 else "%x" % min(15, round(p[x, y][0] / 17)) for x in range(im.width)) for y in range(im.height)]


def footprint(size):
    w, h = size
    return 20 * w + 5 * (w - 1), 20 * h + 7 * (h - 1)


pack = json.load(open(os.path.join(PACK, "pack.json")))
out = {"pieces": {}, "floors": {}, "walls": {}, "roads": {}, "maps": pack.get("maps", {})}
for pid, p in pack.get("pieces", {}).items():
    parts = {name: [rows(f) for f in files] for name, files in p["parts"].items()}
    fw, fh = footprint(p["size"])
    for name, pics in parts.items():
        for pic in pics:
            if not name.startswith(("link", "hl_", "vl_", "corner")) and (len(pic[0]) > fw or len(pic) > fh):
                sys.exit(f"pack: {pid}.{name} is {len(pic[0])}x{len(pic)}, bigger than its {fw}x{fh} footprint")
    out["pieces"][pid] = {k: v for k, v in p.items() if k != "parts"} | {"parts": parts}
for fid, f in pack.get("floors", {}).items():
    out["floors"][fid] = {"tile": [rows(t) for t in f["tile"]]} | {k: f[k] for k in ("panel", "from") if k in f}
    for t in out["floors"][fid]["tile"]:
        if (len(t[0]), len(t)) != (25, 27): sys.exit(f"pack: floor {fid} tile is {len(t[0])}x{len(t)}, not 25x27")
    if "panel" in f and f["panel"][0] * f["panel"][1] != len(f["tile"]):
        sys.exit(f"pack: floor {fid} is a {f['panel'][0]}x{f['panel'][1]} panel but has {len(f['tile'])} tiles")
for wid, w in pack.get("walls", {}).items():
    out["walls"][wid] = {k: rows(w[k]) for k in ("h", "v", "node")} | ({"from": w["from"]} if "from" in w else {})
for rid, r in pack.get("roads", {}).items():
    out["roads"][rid] = {"width": r["width"], "strip": rows(r["strip"]), "corner": rows(r["corner"])} | ({"from": r["from"]} if "from" in r else {})

ts = ["// Generated by tools/pack_build.py from art/pack/ (docs/art.md). Don't edit by hand.",
      "// Pictures are rows of hex levels, '.' see-through, at display size.",
      "",
      "export type Pic = string[];",
      "export type Joins = \"none\" | \"row\" | \"grid\" | \"path\";",
      "export interface PieceDef { size: [number, number]; joins: Joins; decal?: boolean; maps?: string[]; from?: string[]; parts: Record<string, Pic[]> }",
      "export interface FloorDef { tile: Pic[]; panel?: [number, number]; from?: string }",
      "export interface WallKit { h: Pic; v: Pic; node: Pic; from?: string }",
      "export interface RoadKit { width: number; strip: Pic; corner: Pic; from?: string }",
      "export interface MapArt { floor: string; floors: string[]; walls: string; road: string; pieces: string[] }",
      "export interface Pack { pieces: Record<string, PieceDef>; floors: Record<string, FloorDef>; walls: Record<string, WallKit>; roads: Record<string, RoadKit>; maps: Record<string, MapArt> }",
      "",
      "export const PACK: Pack = " + json.dumps(out, separators=(",", ":")) + ";",
      ""]
open(OUT, "w").write("\n".join(ts))
n = sum(len(v) for p in out["pieces"].values() for v in p["parts"].values())
print(f"src/pack.ts: {len(out['pieces'])} pieces ({n} pictures), {len(out['floors'])} floors, {len(out['walls'])} wall kits, {len(out['roads'])} road kits, {os.path.getsize(OUT) // 1024} KB")
